Page({
  data: {
    type: 'terms',
    title: '用户协议',
    updateDate: '2026年9月18日',
    sections: [] as DocSection[],
    faqList: [] as FaqItem[],
    expandedMap: {} as Record<number, boolean>
  },

  onLoad(options: any) {
    const type = options.type || 'terms'
    let title = '用户协议'
    let sections: DocSection[] = []
    let faqList: FaqItem[] = []
    const expandedMap: Record<number, boolean> = {}

    if (type === 'privacy') {
      title = '隐私政策'
      sections = PRIVACY_SECTIONS
    } else if (type === 'faq') {
      title = '常见问题'
      faqList = FAQ_LIST
      // 默认展开第 1 条
      expandedMap[0] = true
    } else {
      title = '用户协议'
      sections = TERMS_SECTIONS
    }

    this.setData({
      type: type,
      title: title,
      sections: sections,
      faqList: faqList,
      expandedMap: expandedMap
    })
  },

  /** 切换常见问题展开/折叠 */
  toggleFaq(e: any) {
    const index = e.currentTarget.dataset.index
    if (typeof index !== 'number') return
    const current = !this.data.expandedMap[index]
    this.setData({
      ['expandedMap.' + index]: current
    })
  }
})
